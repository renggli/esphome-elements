struct Color {
  uint8_t r{255}, g{255}, b{255};
  bool operator==(const Color& o) const { return r == o.r && g == o.g && b == o.b; }
};

static constexpr uint64_t CANARY_VAL = 0xDEADBEEFCAFEBABEULL;

class MockDisplay {
 public:
  MockDisplay(int width, int height) : width_(width), height_(height) {
    size_t count = (width_ > 0 && height_ > 0) ? static_cast<size_t>(width_) * height_ : 0;
    buffer_raw_.resize(count + 2 * CANARY_PADDING, 0);
    // Write canaries
    set_canaries_();
  }

  void reset() {
    pixels_drawn_ = 0;
    oob_writes_ = 0;
    size_t count = (width_ > 0 && height_ > 0) ? static_cast<size_t>(width_) * height_ : 0;
    if (count > 0) {
      std::fill(buffer_raw_.begin() + CANARY_PADDING,
                buffer_raw_.begin() + CANARY_PADDING + count, 0);
    }
    set_canaries_();
  }

  void draw_pixel_at(int x, int y, Color color) {
    if (x < 0 || x >= width_ || y < 0 || y >= height_) {
      oob_writes_++;
      return;
    }
    size_t idx = CANARY_PADDING + static_cast<size_t>(y) * width_ + x;
    buffer_raw_[idx] = 1;
    pixels_drawn_++;
  }

  void line(int x0, int y0, int x1, int y1, Color color) {
    // Bresenham 2D
    int dx = std::abs(x1 - x0);
    int dy = std::abs(y1 - y0);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    while (true) {
      draw_pixel_at(x0, y0, color);
      if (x0 == x1 && y0 == y1) break;
      int e2 = 2 * err;
      if (e2 > -dy) {
        err -= dy;
        x0 += sx;
      }
      if (e2 < dx) {
        err += dx;
        y0 += sy;
      }
    }
  }

  bool check_canaries() const {
    const uint64_t* front = reinterpret_cast<const uint64_t*>(buffer_raw_.data());
    for (size_t i = 0; i < CANARY_PADDING * sizeof(uint8_t) / sizeof(uint64_t); ++i) {
      if (front[i] != CANARY_VAL) return false;
    }
    size_t count = (width_ > 0 && height_ > 0) ? static_cast<size_t>(width_) * height_ : 0;
    const uint64_t* back = reinterpret_cast<const uint64_t*>(buffer_raw_.data() + CANARY_PADDING + count);
    for (size_t i = 0; i < CANARY_PADDING * sizeof(uint8_t) / sizeof(uint64_t); ++i) {
      if (back[i] != CANARY_VAL) return false;
    }
    return true;
  }

  size_t pixels_drawn() const { return pixels_drawn_; }
  size_t oob_writes() const { return oob_writes_; }
  int width() const { return width_; }
  int height() const { return height_; }
  bool is_pixel_set(int x, int y) const {
    if (x < 0 || x >= width_ || y < 0 || y >= height_) return false;
    return buffer_raw_[CANARY_PADDING + static_cast<size_t>(y) * width_ + x] != 0;
  }

 private:
  static constexpr size_t CANARY_PADDING = 64; // 64 bytes before and after
  int width_{0};
  int height_{0};
  std::vector<uint8_t> buffer_raw_;
  size_t pixels_drawn_{0};
  size_t oob_writes_{0};

  void set_canaries_() {
    uint64_t* front = reinterpret_cast<uint64_t*>(buffer_raw_.data());
    for (size_t i = 0; i < CANARY_PADDING * sizeof(uint8_t) / sizeof(uint64_t); ++i) {
      front[i] = CANARY_VAL;
    }
    size_t count = (width_ > 0 && height_ > 0) ? static_cast<size_t>(width_) * height_ : 0;
    uint64_t* back = reinterpret_cast<uint64_t*>(buffer_raw_.data() + CANARY_PADDING + count);
    for (size_t i = 0; i < CANARY_PADDING * sizeof(uint8_t) / sizeof(uint64_t); ++i) {
      back[i] = CANARY_VAL;
    }
  }
};

